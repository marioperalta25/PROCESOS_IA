"""Contratos del chat independientes de Qt y del transporte de Ollama."""

from contextlib import AbstractContextManager
from threading import Event
from typing import Callable, Protocol


class RepositorioConversaciones(Protocol):
    def operacion(self) -> AbstractContextManager: ...
    def existe(self, identificador: str) -> bool: ...
    def leer(self, identificador: str) -> dict: ...
    def guardar_bajo_bloqueo(self, datos: dict) -> None: ...
    def guardar(self, datos: dict, version_esperada: str | None = None) -> None: ...
    def comprobar_respuesta(self, datos: dict) -> None: ...


class GeneradorConversacion(Protocol):
    def __call__(self, mensajes: list[dict], modelo: str, contexto: int,
                 temperatura: float, resumir: bool = False, *,
                 al_fragmento: Callable[[str], None] | None = None,
                 cancelacion: Event | None = None,
                 al_metricas: Callable[[dict], None] | None = None) -> str: ...

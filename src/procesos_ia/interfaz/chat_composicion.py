"""Composición visual nativa del chat, sin navegador ni ventanas emergentes."""

from PySide6.QtCore import Qt
from PySide6.QtWidgets import (
    QComboBox, QHBoxLayout, QLabel, QLineEdit, QListWidget, QPlainTextEdit, QPushButton,
    QScrollArea, QSplitter, QStackedWidget, QVBoxLayout, QWidget,
)
from procesos_ia.interfaz.componentes.barra_navegacion import BarraNavegacionSubvista
from procesos_ia.interfaz.componentes.banner_notificacion import BannerNotificacion
from procesos_ia.interfaz.componentes.editor_texto_expandible import EditorTextoExpandible
from procesos_ia.interfaz.mensajes_chat import PanelMensajes


def construir_chat(vista, textos: dict) -> None:
    vista.setObjectName("chat_local")
    raiz = QVBoxLayout(vista)
    barra = BarraNavegacionSubvista(textos["titulo"], textos["nuevo"], vista)
    barra.btn_volver.setText(textos["volver"])
    barra.btn_limpiar.setText(textos["nuevo"])
    barra.volver_solicitado.connect(vista._volver)
    barra.limpiar_solicitado.connect(vista._nuevo)
    vista.barra_nav = barra
    raiz.addWidget(barra)
    vista.divisor = QSplitter(Qt.Orientation.Horizontal, vista)
    raiz.addWidget(vista.divisor, 1)
    vista.lateral = QWidget(vista)
    vista.lateral.setObjectName("historial_chat")
    vista.lateral.setMinimumWidth(vista.parametros["limites"]["historial_ancho_minimo"])
    lateral = QVBoxLayout(vista.lateral)
    lateral.addWidget(QLabel(textos["historial"], vista))
    vista.lista = QListWidget(vista)
    vista.lista.setWordWrap(True)
    vista.lista.setHorizontalScrollBarPolicy(Qt.ScrollBarPolicy.ScrollBarAlwaysOff)
    vista.lista.setTextElideMode(Qt.TextElideMode.ElideRight)
    vista.lista.setObjectName("lista_chats")
    vista.lista.currentRowChanged.connect(vista._seleccionar)
    lateral.addWidget(vista.lista, 1)
    vista.uso = QLabel(vista)
    vista.uso.setWordWrap(True)
    lateral.addWidget(vista.uso)
    vista.divisor.addWidget(vista.lateral)
    panel = QWidget(vista)
    vista.panel_conversacion = panel
    central = QVBoxLayout(panel)
    fila = QHBoxLayout()
    vista.titulo = QLabel(textos["nuevo"], vista)
    vista.titulo.setTextFormat(Qt.TextFormat.PlainText)
    vista.titulo.setWordWrap(True)
    vista.titulo.setObjectName("titulo_chat")
    fila.addWidget(vista.titulo, 1)
    vista.btn_historial = QPushButton(textos["historial"], vista)
    vista.btn_historial.clicked.connect(vista._alternar_historial)
    barra.layout().addWidget(vista.btn_historial)
    central.addLayout(fila)
    vista.modelo = QLabel(vista)
    vista.modelo.setTextFormat(Qt.TextFormat.PlainText)
    vista.modelo.setWordWrap(True)
    modelos = QHBoxLayout()
    modelos.addWidget(vista.modelo, 1)
    vista.combo_modelos = QComboBox(vista)
    vista.combo_modelos.setSizeAdjustPolicy(QComboBox.SizeAdjustPolicy.AdjustToMinimumContentsLengthWithIcon)
    vista.combo_modelos.setAccessibleName(textos["elegir_modelo"])
    modelos.addWidget(vista.combo_modelos, 1)
    vista.btn_modelos = QPushButton(textos["actualizar_modelos"], vista)
    vista.btn_modelos.clicked.connect(vista.solicitar_actualizacion_modelos.emit)
    modelos.addWidget(vista.btn_modelos)
    central.addLayout(modelos)
    acciones = QHBoxLayout()
    for nombre, clave, funcion in (
        ("btn_renombrar", "renombrar", vista._editar_nombre),
        ("btn_memoria", "memoria", vista._editar_memoria),
        ("btn_borrar", "borrar", vista._pedir_borrado),
    ):
        boton = QPushButton(textos[clave], vista)
        boton.clicked.connect(funcion)
        setattr(vista, nombre, boton)
        acciones.addWidget(boton)
    central.addLayout(acciones)
    vista.banner = BannerNotificacion(vista)
    vista.banner.mostrar_info(textos["listo"])
    central.addWidget(vista.banner)
    vista.contenido = QStackedWidget(vista)
    central.addWidget(vista.contenido, 1)
    vista.editor = QWidget(vista)
    marco_editor = QVBoxLayout(vista.editor)
    marco_editor.setContentsMargins(0, 0, 0, 0)
    vista.area_editor = QScrollArea(vista.editor)
    vista.area_editor.setWidgetResizable(True)
    marco_editor.addWidget(vista.area_editor, 1)
    panel_editor = QWidget(vista.area_editor)
    vista.area_editor.setWidget(panel_editor)
    edicion = QVBoxLayout(panel_editor)
    vista.nombre = QLineEdit(vista)
    vista.nombre.setPlaceholderText(textos["nombre"])
    vista.nombre.setMaxLength(vista.parametros["limites"]["titulo_caracteres"])
    limites = vista.parametros["limites"]
    vista.resumen = EditorTextoExpandible(
        altura_inicial=limites["memoria_editor_alto"], altura_min=limites["memoria_editor_alto_minimo"],
        altura_max=limites["memoria_editor_alto_maximo"], placeholder=textos["resumir"], parent=panel_editor,
    )
    vista.resumen.editor.setAcceptRichText(False)
    edicion.addWidget(vista.nombre)
    edicion.addWidget(vista.resumen)
    botones = QHBoxLayout()
    vista.btn_confirmar = QPushButton(vista)
    vista.btn_confirmar.clicked.connect(vista._confirmar_edicion)
    cancelar = QPushButton(textos["cancelar"], vista)
    cancelar.clicked.connect(vista._cerrar_editor)
    botones.addWidget(vista.btn_confirmar)
    botones.addWidget(cancelar)
    marco_editor.addLayout(botones)
    vista.contenido.addWidget(vista.editor)
    vista.transcripcion = PanelMensajes(vista.parametros, vista)
    vista.contenido.addWidget(vista.transcripcion)
    vista.contenido.setCurrentWidget(vista.transcripcion)
    vista.entrada = QPlainTextEdit(vista)
    vista.entrada.setPlaceholderText(textos["entrada"])
    vista.entrada.setMaximumHeight(vista.parametros["limites"]["entrada_alto_maximo"])
    vista.entrada.installEventFilter(vista)
    vista.entrada.textChanged.connect(vista._guardar_borrador)
    central.addWidget(vista.entrada, 0)
    enviar = QHBoxLayout()
    vista.btn_reintentar = QPushButton(textos["reintentar"], vista)
    vista.btn_reintentar.clicked.connect(lambda: vista._enviar(reintentar=True))
    enviar.addWidget(vista.btn_reintentar)
    enviar.addStretch()
    vista.btn_enviar = QPushButton(textos["enviar"], vista)
    vista.btn_enviar.setObjectName("btn_principal")
    vista.btn_enviar.clicked.connect(lambda: vista._enviar())
    enviar.addWidget(vista.btn_enviar)
    central.addLayout(enviar)
    vista.divisor.addWidget(panel)
    vista.divisor.setStretchFactor(0, 1)
    vista.divisor.setStretchFactor(1, 3)
